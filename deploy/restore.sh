#!/usr/bin/env bash
#
# Restore a Foyer installation from a backup taken by deploy/backup.sh.
#
#   deploy/restore.sh                              # the newest backup
#   deploy/restore.sh <dump>                       # a named one
#   deploy/restore.sh --list                       # what is there, no restore
#   deploy/restore.sh --kek <file> <dump>          # the KEK from somewhere else
#   deploy/restore.sh --dry-run <dump>             # check it, change nothing
#   deploy/restore.sh --yes                        # no question asked
#
# Run on the host, as the deploy user. It puts the data back and leaves the
# installation standing.
#
# ── why this exists at all ───────────────────────────────────────────────────
#
# A backup is only worth the restore that has been executed against it, and a
# restore procedure that omits the KEK restores nothing usable. This is that
# procedure, and `tools/deploycheck` executes it.
#
# ── the KEK, and the decision ────────────────────────────────────────────────
#
# **The KEK is required separately, and this script refuses without it by name.**
# That is the decision. The three alternatives, and why:
#
#   * *Include the KEK in the backup.* Rejected. A backup directory is the thing
#     most likely to be copied somewhere less protected — that is what a backup
#     is for — and a copy carrying the key is a copy of every shared secret,
#     every controller credential and every NT hash in the venue. It turns
#     "somebody has our backups" from a disclosure of guest data into a
#     disclosure of the RADIUS server.
#
#   * *Include it, encrypted under a passphrase.* Right for a laptop, and wrong
#     here for one specific reason: **there is nowhere on this host to keep a
#     passphrase that is not this host.** An escrow whose passphrase is escrowed
#     beside it protects nothing, and the operator who has to invent one at 02:00
#     during an outage will not have it. A secret store is a design of its
#     own, and a half of one would be worse than refusing.
#
#   * *Refuse without it, and say exactly what is missing.* **Chosen.** The
#     operator's job is then one sentence: **keep a copy of
#     /opt/foyer/secrets/kek somewhere this host's disk failure cannot reach.**
#
# And the refusal names the object, because `internal/store/envelope.go` prefixes
# every sealed value with `FKv` and the key id. A restored-without-the-KEK
# database is not subtly wrong; it is a table of `FKv2026-09` and bytes, and
# "the restore failed" would send an operator to look at PostgreSQL.
#
# ── what this restores, and what it does not ─────────────────────────────────
#
#   RESTORED  the database — venues, vouchers, accounts, sessions, audit rows,
#             and every sealed column, **provided the KEK matches**.
#   NOT       /opt/foyer/secrets. The database passwords, the TLS material and
#             the maintenance token are regenerated by `first-boot.sh`, and the
#             operator's administrator survives **because the database survives**:
#             the argon2id verifier is in the dump. That is the point of the KEK
#             decision — an operator signs in to a restored console with the
#             password they already had, and no administrator has to be re-made.
#
set -euo pipefail

FOYER_ROOT="${FOYER_ROOT:-/opt/foyer}"
SRC="${FOYER_ROOT}/src"
# STATE is read by deploy/backups.sh, which is sourced below and sets BACKUPS
# from it — the same shape secretdirs.sh and consolenames.sh rely on.
# shellcheck disable=SC2034
STATE="${FOYER_ROOT}/state"
SECRETS="${FOYER_ROOT}/secrets"

die()  { printf 'restore: %s\n' "$*" >&2; exit 1; }
say()  { printf '\n==> %s\n' "$*"; }
note() { printf '    %s\n' "$*"; }

# The naming, the fingerprint and the manifest fields come from deploy/backups.sh
# rather than being written again here. `backup.sh` and `verify.sh` read the same
# three, and **a fingerprint computed two ways is a fingerprint that eventually
# disagrees with itself** — and the disagreement surfaces as "this backup does
# not match your KEK" on an installation where nothing is wrong.
# shellcheck source=backups.sh
. "${SRC}/deploy/backups.sh"

as_root() { if [[ $EUID -eq 0 ]]; then bash "$@"; else sudo bash "$@"; fi; }
compose() { PGPASSWORD="${PGPASS}" "${SRC}/deploy/compose.sh" "$@"; }

PGPASS=""

# ── arguments ────────────────────────────────────────────────────────────────
dump=""; kek="${SECRETS}/kek"; dry=0; assume_yes=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --list)    [[ -d "${BACKUPS}" ]] || die "${BACKUPS} does not exist; nothing has been backed up"
               printf 'backup\tage\tkek fingerprint\n'
               foyer_backup_list
               exit 0 ;;
    --kek)     kek="$2"; shift 2 ;;
    --dry-run) dry=1; shift ;;
    --yes)     assume_yes=1; shift ;;
    -*)        die "unknown option $1" ;;
    *)         dump="$1"; shift ;;
  esac
done

# ── which dump ───────────────────────────────────────────────────────────────
#
# Newest when not named: an operator at 02:00 should not have to know a
# timestamp, and "the most recent one" is the answer almost every time. Sorted on
# mtime by the shared helper, so this agrees with what `backup.sh --list` prints
# and with the order `backup.sh` pruned in.
if [[ -z "${dump}" ]]; then
  dump="$(foyer_backups_newest_first | head -1)"
  [[ -n "${dump}" ]] || die "no backup in ${BACKUPS}. Run deploy/backup.sh, or --list to see what is there"
fi
[[ -s "${dump}" ]] || die "${dump} does not exist or is empty"
manifest="${dump%.dump}.manifest"
[[ -s "${manifest}" ]] || die "${manifest} is missing.
         Without it nothing can say which KEK opens this dump, and a restore that
         cannot check is the failure this script exists to prevent."

say "Restoring $(basename "${dump}")"
note "taken   $(foyer_backup_manifest_field "${dump}" taken  || echo unknown)"
note "schema  $(foyer_backup_manifest_field "${dump}" schema || echo unknown)"
note "sha256  $(foyer_backup_manifest_field "${dump}" sha256 || echo unknown)"

# The dump's own checksum, **before anything is destroyed**. A corrupt dump
# restored on top of a working installation is strictly worse than no restore:
# the operator has given up a good database for a bad one and finds out after.
actual="$(foyer_sha256 "${dump}")"
if [[ "${actual}" != "$(foyer_backup_manifest_field "${dump}" sha256 || true)" ]]; then
  die "${dump} does not match the sha256 in its manifest.
         The file has changed since the backup was written, or the disk is failing.
         Nothing has been touched. Get another copy before restoring this one."
fi
note "checksum matches its manifest"

# ── the KEK, refused by name ─────────────────────────────────────────────────
#
# This is the block the whole file is arranged around. Every branch says what is
# missing **and what it costs**, because "permission denied" at 02:00 does not
# tell an operator that the thing they are missing decrypts their entire venue.
want="$(foyer_backup_manifest_field "${dump}" kek-sha256 || echo none)"

if [[ ! -s "${kek}" ]]; then
  cat >&2 <<EOF
restore: no key-encryption key, so this dump cannot be read.

         ${kek} does not exist, or is empty.

         A Foyer backup holds every RADIUS shared secret, every controller
         credential and every NT hash as CIPHERTEXT. internal/store/envelope.go
         seals each one under FOYER_KEK, and the key is deliberately NOT in the
         database it protects: every sealed value begins FKv and the key id, and
         is AES-GCM ciphertext after that. Without the KEK this dump restores a
         database nobody can read a single secret out of.

         The manifest for this dump records the KEK it was taken with:
             sha256 ${want}

         Supply it with --kek <path-to-the-kek-file>, or put a copy at
             ${kek}
         and run this again. Nothing has been touched.
EOF
  exit 1
fi

have="$(foyer_kek_fingerprint "${kek}")"
if [[ "${want}" != "none" && "${have}" != "${want}" ]]; then
  cat >&2 <<EOF
restore: this is the WRONG key-encryption key.

         the dump was taken under a KEK whose sha256 is
             ${want}
         and ${kek} hashes to
             ${have}

         Restoring it anyway would produce an installation that starts, serves a
         console, and cannot decrypt one shared secret, one controller credential
         or one NT hash. Nobody would find out until a guest's voucher stopped
         working or a controller refused to register.

         Find the KEK that matches the sha256 above and pass it with
             --kek <path>
         Nothing has been touched.
EOF
  exit 1
fi
note "KEK sha256 ${have} — matches the manifest"

# ── dry run stops here ───────────────────────────────────────────────────────
#
# After the KEK check and before anything is stopped, dropped or recreated. That
# ordering is the whole point: a dry run that reported "fine" and then turned out
# to hold no key would be worse than no dry run at all.
if (( dry )); then
  say "Dry run"
  note "the dump is intact, its checksum matches, and this KEK opens it"
  note "nothing was stopped, dropped or recreated"
  exit 0
fi

# ── the question ─────────────────────────────────────────────────────────────
#
# A typed confirmation, because this destroys the database, and "I ran the
# restore script" should never be something an operator discovers afterwards.
if (( assume_yes == 0 )); then
  cat <<EOF
This replaces the database on this host with the contents of

    $(basename "${dump}")

Every venue, voucher, account, session and audit row currently in PostgreSQL is
destroyed. They come back — from the dump — but only up to the moment that dump
was taken, and anything written since then is gone.

EOF
  read -r -p "  Type 'restore ${HOSTNAME:-this host}' to continue: " answer
  [[ "${answer}" == "restore ${HOSTNAME:-this host}" ]] || die "not confirmed; nothing was touched"
fi

[[ -f "${SRC}/deploy/compose.sh" ]] || die "${SRC}/deploy/compose.sh is not there. Run deploy/sync.sh first."
[[ -s "${SECRETS}/postgres_password" ]] || die "${SECRETS}/postgres_password is missing. Run: sudo bash ${SRC}/deploy/first-boot.sh --secrets-only"
PGPASS="$(cat "${SECRETS}/postgres_password")"

# ── 1. stop everything that reads the database ───────────────────────────────
#
# The application first, and PostgreSQL never. A `pg_restore` into a live
# database is a restore nobody can reason about afterwards, and the control plane
# holding a pool open while the schema underneath it changes is the same class
# of mistake upgrade.sh's step 5 exists to prevent.
say "Stopping the application"
compose stop foyer freeradius maintenance || true
note "the portal and RADIUS are down from here until the last step"

# ── 2. recreate the database ─────────────────────────────────────────────────
#
# DROP and CREATE, not `pg_restore --clean`. A --clean restore runs every DROP
# against whatever is there and fails part way on any object it did not expect,
# leaving a schema that is neither the old one nor the dump. Dropping first means
# the restore either lands whole or leaves an empty database, and the second is a
# state an operator can see from `psql`.
say "Recreating the database"
compose exec -T -e PGPASSWORD="${PGPASS}" postgres \
  psql -U foyer -d postgres -v ON_ERROR_STOP=1 \
  -c "DROP DATABASE IF EXISTS foyer WITH (FORCE)" \
  -c "CREATE DATABASE foyer OWNER foyer" >/dev/null
note "an empty database named foyer"

# ── 3. restore ───────────────────────────────────────────────────────────────
#
# `--exit-on-error`, so a restore that cannot finish stops here with a partly
# populated database and says so, rather than reporting success over a schema
# with holes in it. `ON_ERROR_STOP` above is the same rule one level up.
#
# **`--no-acl` is not passed here either**, for the reason given in
# `backup.sh`: a restore that drops the GRANT statements produces a database
# with the right tables and none of the privileges on them, and the control plane
# then refuses to start with "permission denied for table network_settings" —
# which looks like a broken image and is a restore that threw away the
# privileges. `--no-owner` is still right: the objects belong to `foyer` on both
# sides.
say "Loading the dump"
if ! compose exec -T -e PGPASSWORD="${PGPASS}" postgres \
      pg_restore -U foyer -d foyer --exit-on-error --no-owner < "${dump}"; then
  printf '\n' >&2
  echo "restore: the dump did not load. NOTHING HAS BEEN STARTED." >&2
  echo "         The database is empty or partly restored, and nothing is serving" >&2
  echo "         guests against it. The dump is untouched at ${dump}." >&2
  echo "" >&2
  echo "         The usual cause is a dump from a NEWER schema than this tree's" >&2
  echo "         migrations. This dump records the schema it was taken with:" >&2
  echo "             $(foyer_backup_manifest_field "${dump}" schema || echo unknown)" >&2
  echo "         and this tree is $(cat "${SRC}/.shipped-rev" 2>/dev/null || echo unknown)." >&2
  exit 1
fi
note "loaded"

# ── 4. the logins, because the dump does not carry them ──────────────────────
#
# **This is the step that makes a restored installation able to log in at all,
# and it is not in the dump.** `pg_dump` stores password *verifiers*, not
# passwords, and `first-boot.sh` generated each login's password into a file the
# dump never saw. Restored into a fresh cluster, `foyer_app` and its siblings
# have no password at all — so this re-sets them from the files on this host.
# Skip it and the restored database is a database nothing can connect to.
say "Restoring the database logins"
as_root "${SRC}/deploy/first-boot.sh" --secrets-only >/dev/null
FOYER_DATABASE_URL_FILE="${SECRETS}/owner_database_url" \
FOYER_KEK_FILE="${SECRETS}/kek" \
  "${SRC}/deploy/compose.sh" run --rm migrate >/dev/null
note "foyer_app, foyer_radius, foyer_reaper and foyer_retention can log in again"

# ── 5. up, and prove it ──────────────────────────────────────────────────────
say "Starting"
compose up -d
ready=0
for _ in $(seq 1 60); do
  if compose exec -T foyer wget --no-check-certificate -q -O- https://127.0.0.1:8443/healthz >/dev/null 2>&1; then
    ready=1; break
  fi
  sleep 2
done
[[ ${ready} -eq 1 ]] || die "the control plane did not become healthy. ${SRC}/deploy/compose.sh logs foyer"

say "Verifying"
bash "${SRC}/deploy/verify.sh" || true

cat <<EOF

    ────────────────────────────────────────────────────────────────────────────
    Restored $(foyer_backup_manifest_field "${dump}" taken || echo unknown).

    Sign in to the console with the password you had before. The argon2id
    verifier came back in the dump; nothing about the administrator changed.

    This restored the DATABASE. If the host itself was rebuilt, the secrets in
    ${SECRETS} were regenerated — this is a complete recovery of the venue, not
    of the machine.

    Keep a record of this restore.
    ────────────────────────────────────────────────────────────────────────────

EOF
