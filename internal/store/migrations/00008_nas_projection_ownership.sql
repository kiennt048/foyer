COMMENT ON COLUMN nas.radius_client_id IS NULL;
COMMENT ON COLUMN nas.tenant_id IS NULL;
COMMENT ON COLUMN nas.limit_proxy_state IS NULL;
COMMENT ON COLUMN nas.require_message_authenticator IS NULL;
COMMENT ON COLUMN nas.secret IS NULL;
COMMENT ON TABLE nas IS NULL;

DROP INDEX nas_tenant_idx;
ALTER TABLE nas DROP COLUMN radius_client_id;
ALTER TABLE nas DROP COLUMN tenant_id;
