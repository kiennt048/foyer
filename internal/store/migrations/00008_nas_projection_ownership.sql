-- What the `nas` projection is, who owns each row, and which of its columns do
-- nothing.
--
-- Migration 00002 created `nas` and said, correctly, that it is the table
-- FreeRADIUS reads with `read_clients = yes` and that `radius_clients` is the
-- system of record. What it could not say -- because the sync did not exist yet --
-- is what happens when the two disagree. This migration adds the two columns that
-- make the answer expressible, and writes down the one thing about this table that
-- a reader will otherwise get wrong from the column names alone.
--
-- ---------------------------------------------------------------------------
-- 1. Two of this table's columns are inert.
-- ---------------------------------------------------------------------------
--
-- `rlm_sql` reads exactly six columns for a client -- id, nasname, shortname, type,
-- secret, server -- and maps them positionally. There is no seventh and
-- `client_query` cannot carry one. So `nas.require_message_authenticator` and
-- `nas.limit_proxy_state` are read by nothing: setting either to false changes
-- nothing about how the server treats that client.
--
-- They are not wrong to have. They are what `radius_clients` declares and what the
-- console shows an operator. But a column named `require_message_authenticator` in
-- the table FreeRADIUS reads looks exactly like the switch that enforces
-- BlastRADIUS protection, and it is not one. The guarantee lives in three other
-- places, all generated by `internal/raddb`: `security {}` in radiusd.conf, the
-- network sections in clients.conf, and `&FreeRADIUS-Client-Require-MA` per
-- discovered client in sites-available/dynamic-clients.
--
-- The COMMENTs below are the point of this half of the migration: `\d+ nas` is
-- where somebody checking this will look, and until now it said nothing.
--
-- ---------------------------------------------------------------------------
-- 2. Who owns a row, so that removing one is possible.
-- ---------------------------------------------------------------------------
--
-- The sync (`Store.NasProjection().Sync`) has to remove as well as add: a
-- decommissioned access point that keeps its RADIUS client is a security defect,
-- not an untidiness. Removing means deleting every row the system of record no
-- longer produces -- which is only safe if a row says whose it is.
--
-- `tenant_id` is that. The DELETE is scoped to `foyer_current_tenant()`, the same
-- function every row-level policy in this schema compares against, so a sync run
-- for one tenant cannot erase another's clients. It is scoped to NULL as well,
-- because a row with no tenant is a row no sync produced -- see the long note on
-- the column below, which is where it says why NOT NULL is wrong.
--
-- **`nas` still has no row-level policy, and must not get one.** FreeRADIUS
-- connects as `foyer_radius` and never sets the tenant GUC; an unset GUC is NULL,
-- every policy here compares with `=`, and the result would be a server that loads
-- no clients at all and discards every packet. The protection on this table is the
-- GRANT -- `foyer_radius` may SELECT and nothing else -- and the tenant column is
-- for the writer's benefit, not the reader's.
--
-- One consequence is worth stating rather than discovering: `nas.nasname` is
-- globally UNIQUE while `radius_clients` is UNIQUE (tenant_id, address). Two
-- tenants may legitimately hold the same NAS address and only one of them can be
-- projected, because FreeRADIUS's client list is a flat global namespace with no
-- tenant in it. The sync reports that as a conflict naming the address rather than
-- quietly taking the row over.

-- +goose Up

ALTER TABLE nas ADD COLUMN tenant_id uuid REFERENCES tenants(id) ON DELETE CASCADE;
ALTER TABLE nas ALTER COLUMN tenant_id SET DEFAULT foyer_current_tenant();

-- **Nullable, because NOT NULL is measured wrong.**
--
-- `foyer_current_tenant()` reads the `foyer.tenant_id` GUC and returns NULL when
-- it is unset, so the DEFAULT above evaluates to NULL for every writer that is not
-- `internal/store` -- and `SET NOT NULL` with a backfill of the default tenant
-- would turn that into a refusal. Two writers in this repository are exactly that
-- shape, and both are outside `internal/store`:
--
--   lab/policy/sigstop_test.go   registers the harness's own client over a plain
--                                pgx connection, as an operator would
--   lab/blue-green/seed-client.sh   the same INSERT from psql, and the script the
--                                blue/green gates use to prove that adding an
--                                access point is `sql-only`
--
-- MEASURED with NOT NULL applied: `go test ./...` fails with
-- `null value in column "tenant_id" of relation "nas" violates not-null
-- constraint`, in the SIGSTOP test -- the one docs/rules/radius.md calls the
-- test that proves this architecture was worth choosing. The comment on
-- radius_client_id, below, says a row may be seeded by hand and names that
-- script; NOT NULL would forbid it.
--
-- So NULL is a real state and it means what it says: **no tenant's sync produced
-- this row.** Sync claims such a row if its address is one this tenant's system of
-- record produces, and deletes it otherwise -- see the DELETE in
-- internal/store/nassync.go, which is scoped
-- `tenant_id = foyer_current_tenant() OR tenant_id IS NULL`.
--
-- The rejected alternative was DEFAULT coalesce(foyer_current_tenant(),
-- '00000000-...-0001'), which keeps NOT NULL by attributing every hand-seeded row
-- to the tenant v1 happens to ship. That is a lie a query cannot see through: the
-- conflict error below would then report an address as `held by tenant <default>`
-- when in fact nobody holds it, and NasAddressConflict already carries the
-- distinction (OtherClientID empty means "seeded by hand"). A column that cannot
-- say "nobody" has to invent somebody.
--
-- There is deliberately no backfill. A row that existed before this migration was
-- put there by something this schema has no record of, which is precisely the
-- state NULL describes.

-- Which `radius_clients` row produced this projection row.
--
-- Deliberately NOT a foreign key. An `ON DELETE CASCADE` here would remove the
-- projection row the instant the client row was deleted -- without the sync having
-- run at all. The test that proves the sync removes a decommissioned client would
-- then pass whether or not the sync's DELETE worked, because a second mechanism
-- fires first and the observable is identical. A negative test whose subject has
-- more than one way to succeed is not yet a test.
--
-- It is nullable because a row may be seeded by hand -- `lab/blue-green/seed-client.sh`
-- does exactly that -- and such a row has no system of record behind it. The sync
-- removes those too, which is the intended behaviour and is stated in CONTRACT.md.
ALTER TABLE nas ADD COLUMN radius_client_id text;

CREATE INDEX nas_tenant_idx ON nas (tenant_id);

COMMENT ON TABLE nas IS
    'Projection, not a system of record. FreeRADIUS reads it with read_clients = yes; '
    'internal/store writes it from radius_clients JOIN shared_secrets. Never edit a row by hand: '
    'the next sync removes anything the system of record does not produce. '
    'This table holds the one declared cleartext copy of a RADIUS shared secret, because '
    'FreeRADIUS validates Message-Authenticator against the secret itself and cannot use an '
    'encrypted one.';

COMMENT ON COLUMN nas.secret IS
    'Cleartext, and the only cleartext copy in the deployment. The system of record is '
    'shared_secrets.secret, envelope-encrypted under a key that is not in this database.';

COMMENT ON COLUMN nas.require_message_authenticator IS
    'INERT. rlm_sql reads six columns for a client (id, nasname, shortname, type, secret, server) '
    'and there is no seventh, so nothing reads this. BlastRADIUS protection is enforced by '
    'security {} in radiusd.conf, by the network sections in clients.conf, and by '
    'FreeRADIUS-Client-Require-MA in sites-available/dynamic-clients.';

COMMENT ON COLUMN nas.limit_proxy_state IS
    'INERT, for the same reason as require_message_authenticator.';

COMMENT ON COLUMN nas.tenant_id IS
    'Which tenant''s sync owns this row, or NULL for a row no sync produced -- a hand-seeded one, '
    'such as lab/blue-green/seed-client.sh writes. NULL is a real state and not a missing value: '
    'the DEFAULT is foyer_current_tenant(), which is NULL for any writer that has not set the '
    'foyer.tenant_id GUC, and NOT NULL here refuses that writer outright. '
    'There is no row-level policy on this table and there must not be: FreeRADIUS never sets the '
    'tenant GUC, and an unset GUC would match no rows and load no clients.';

COMMENT ON COLUMN nas.radius_client_id IS
    'The radius_clients row this was projected from, or NULL for a hand-seeded row. Not a '
    'foreign key on purpose: a cascade would delete this row without the sync running, and the '
    'test that the sync removes a decommissioned client would then pass while the sync was broken.';

