#!/bin/sh
# Generate a throwaway CA, a server certificate and a client certificate for
# the gate-3 EAP-TLS case, plus the eapol_test configuration that uses them.
#
# Nothing this produces is committed and nothing is baked into an image. A CA in
# an image means every deployment on earth shares one private key, and the
# repository's rule against that has no lab exception — so the lab generates its
# own, on the machine, at test time, and throws it away.
#
# EAP-TLS is the first method to get a case for a reason that is not
# convenience: it is the only one where the server holds no recoverable
# credential material at all. Every other method forces a decision about
# credential storage, and those decisions belong with the schema that carries
# them rather than with a test harness.
#
# Environment:
#   EAP_DIR   where to put everything   (default /var/lib/foyer/eap-certs)
#   DAYS      certificate lifetime      (default 30)
set -eu

EAP_DIR=${EAP_DIR:-/var/lib/foyer/eap-certs}
DAYS=${DAYS:-30}

mkdir -p "$EAP_DIR"
cd "$EAP_DIR"
umask 077

cat >openssl-ext.cnf <<'EOF'
[server]
basicConstraints = CA:FALSE
keyUsage = digitalSignature, keyEncipherment
extendedKeyUsage = serverAuth
subjectAltName = DNS:foyer-lab-radius.invalid

[client]
basicConstraints = CA:FALSE
keyUsage = digitalSignature
extendedKeyUsage = clientAuth
EOF

openssl req -x509 -newkey rsa:2048 -nodes -days "$DAYS" \
	-keyout ca.key -out ca.pem \
	-subj "/O=Foyer lab/CN=Foyer lab throwaway CA" >/dev/null 2>&1

openssl req -newkey rsa:2048 -nodes -keyout server.key -out server.csr \
	-subj "/O=Foyer lab/CN=foyer-lab-radius.invalid" >/dev/null 2>&1
openssl x509 -req -in server.csr -CA ca.pem -CAkey ca.key -CAcreateserial \
	-days "$DAYS" -extfile openssl-ext.cnf -extensions server \
	-out server.pem >/dev/null 2>&1

openssl req -newkey rsa:2048 -nodes -keyout client.key -out client.csr \
	-subj "/O=Foyer lab/CN=foyer-eap-tls-probe" >/dev/null 2>&1
openssl x509 -req -in client.csr -CA ca.pem -CAkey ca.key -CAcreateserial \
	-days "$DAYS" -extfile openssl-ext.cnf -extensions client \
	-out client.pem >/dev/null 2>&1

rm -f server.csr client.csr

# radiusd drops to `freerad` before rlm_eap opens server.key, so the server's
# half is granted to the image's foyer-radius-tls group. The CA key and the
# client's half stay owner-only: radiusd needs neither.
if getent group foyer-radius-tls >/dev/null 2>&1; then
	chgrp foyer-radius-tls server.key server.pem ca.pem
	chmod 0640 server.key
	chmod 0644 server.pem ca.pem
fi

cat >eap-tls.conf <<EOF
# eapol_test configuration for the gate-3 EAP-TLS case. Generated by
# make-eap-certs.sh; the paths are absolute because eapol_test does not resolve
# them relative to the configuration file.
network={
	key_mgmt=WPA-EAP
	eap=TLS
	identity="foyer-eap-tls-probe"
	ca_cert="$EAP_DIR/ca.pem"
	client_cert="$EAP_DIR/client.pem"
	private_key="$EAP_DIR/client.key"
	private_key_passwd=""
	eapol_flags=0
}
EOF

echo "$EAP_DIR"
