// Command vendorevidence writes `internal/nas`'s evidence tables into the
// TypeScript world, so that `web/mock` can answer `getNasEvidence` without a
// second copy of them being typed by hand.
//
// # Why this exists rather than a fixture somebody maintains
//
// `docs/rules/testing.md` records four separate instances of the same defect:
// **a stale second copy of a rule whose authority was sitting right there.** One
// of them was a capability set beside `unifi.go`. Hand-transcribing seventeen
// kilobytes of vendor evidence into `web/fixtures` would be the fifth, and the
// worst of them — a fake asserting that a Cisco encoding is documented, inside a
// test suite whose entire premise is that nothing here has ever met a Cisco
// device.
//
// So the mock's copy is generated from the Go authority, the same way
// `web/contract/src/generated/types.ts` is generated from the contract and never
// edited. `make generate-check` fails if the committed file has drifted.
//
// The driver→vendor table is generated too, and for the same reason: it is a rule,
// `nas.VendorForDriver` owns it, and a `switch` retyped in TypeScript is a rule in
// two languages.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"sort"

	"github.com/kiennt048/foyer/internal/api/gen"
	"github.com/kiennt048/foyer/internal/nas"
)

type fact struct {
	Subject  string `json:"subject"`
	Evidence string `json:"evidence"`
	Note     string `json:"note"`
}

type entry struct {
	Capabilities []fact `json:"capabilities"`
	Attributes   []fact `json:"attributes"`
}

func facts[M ~map[string]nas.CapabilityFact](m M) []fact {
	out := make([]fact, 0, len(m))
	for subject, f := range m {
		out = append(out, fact{Subject: subject, Evidence: nas.EvidenceLower(f.Evidence), Note: f.Note})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Subject < out[j].Subject })
	return out
}

func main() {
	// Driven from the contract's own enums, so a sixth driver or a third CoA
	// vendor appears here the moment the contract declares it — rather than the
	// day somebody remembers to add it.
	drivers := []gen.NasDriverKind{
		gen.NasDriverKindUnifi, gen.NasDriverKindOmada, gen.NasDriverKindMikrotik,
		gen.NasDriverKindRuckus, gen.NasDriverKindCoa,
	}
	coaVendors := []gen.CoaVendor{gen.Cisco, gen.Aruba}

	byDriver := map[string]string{}
	vendors := map[string]bool{}
	for _, d := range drivers {
		candidates := []string{""}
		if d == gen.NasDriverKindCoa {
			candidates = nil
			for _, v := range coaVendors {
				candidates = append(candidates, string(v))
			}
		}
		for _, cv := range candidates {
			v, ok := nas.VendorForDriver(string(d), cv)
			if !ok {
				continue
			}
			key := string(d)
			if cv != "" {
				key += ":" + cv
			}
			byDriver[key] = string(v)
			vendors[string(v)] = true
		}
	}

	evidence := map[string]entry{}
	for v := range vendors {
		caps, attrs := nas.EvidenceFor(nas.Vendor(v))
		evidence[v] = entry{Capabilities: facts(caps), Attributes: facts(attrs)}
	}

	byDriverJSON, err := json.MarshalIndent(byDriver, "", "  ")
	if err != nil {
		fail(err)
	}
	evidenceJSON, err := json.MarshalIndent(evidence, "", "  ")
	if err != nil {
		fail(err)
	}

	out := fmt.Sprintf(`/**
 * GENERATED by tools/codegen/vendorevidence. DO NOT EDIT.
 *
 * `+"`internal/nas`"+`'s evidence tables, in the TypeScript world, so `+"`web/mock`"+` can
 * answer `+"`getNasEvidence`"+` from the same authority the Go server answers from.
 *
 * Regenerate with `+"`make generate`"+`; `+"`make generate-check`"+` fails if this file has
 * drifted from `+"`internal/nas`"+`.
 *
 * **Hand-editing this file makes the mock a stale second copy of a rule whose
 * authority is one directory away**, which is the defect `+"`docs/rules/testing.md`"+`
 * records four separate instances of.
 */

export type VendorEvidenceStanding = "measured" | "documented" | "unverified";

export interface VendorEvidenceFact {
  subject: string;
  evidence: VendorEvidenceStanding;
  note: string;
}

export interface VendorEvidenceEntry {
  capabilities: VendorEvidenceFact[];
  attributes: VendorEvidenceFact[];
}

/**
 * Which vendor profile answers for a device, keyed by the driver name, or by
 * driver + ":" + coaVendor for the CoA family.
 *
 * A key that is absent is the case that must never be defaulted: a `+"`coa`"+` row that
 * names no vendor. Cisco and Aruba identify a session differently and a wrong guess
 * is an ACK with no effect — the one failure a fake NAS cannot produce.
 */
export const VENDOR_BY_DRIVER: Record<string, string> = %s;

export const VENDOR_EVIDENCE: Record<string, VendorEvidenceEntry> = %s;
`, byDriverJSON, evidenceJSON)

	if err := os.WriteFile("web/fixtures/src/generated/vendor-evidence.ts", []byte(out), 0o644); err != nil {
		fail(err)
	}
	fmt.Println("  generated web/fixtures/src/generated/vendor-evidence.ts")
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "vendorevidence:", err)
	os.Exit(1)
}
